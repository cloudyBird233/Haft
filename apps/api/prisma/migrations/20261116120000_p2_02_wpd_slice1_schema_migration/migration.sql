-- ---------------------------------------------------------------------------
-- 6. Historical backfill (runs before any trigger exists)
-- ---------------------------------------------------------------------------

-- `completed` and `failed` map deterministically: both are API-observed
-- outcomes, not inferred ones. `terminalDecidedAt` keeps the historical instant
-- but normalises its storage to the L2 v1.1 representation: an INTEGER number of
-- Unix milliseconds. Prisma already stores DateTime as INTEGER, while a legacy
-- row written as an ISO-8601 string is converted exactly (seconds * 1000 plus
-- the millisecond fraction); the instant is never replaced by "now".
UPDATE "Execution"
SET "terminalDecision" = CASE "status"
        WHEN 'completed' THEN 'COMPLETED'
        WHEN 'failed' THEN 'EXECUTION_FAILED'
    END,
    "terminalDecidedAt" = CASE typeof(COALESCE("endedAt", "updatedAt"))
        WHEN 'integer' THEN COALESCE("endedAt", "updatedAt")
        WHEN 'real' THEN CAST(COALESCE("endedAt", "updatedAt") AS INTEGER)
        ELSE CAST(strftime('%s', COALESCE("endedAt", "updatedAt")) AS INTEGER) * 1000
             + CAST(substr(strftime('%f', COALESCE("endedAt", "updatedAt")), 4, 3) AS INTEGER)
    END,
    "terminalDecidedBy" = 'MIGRATION:wp-d-backfill',
    "dispatchState" = 'terminal'
WHERE "status" IN ('completed', 'failed');

-- Legacy cancellations are terminal but carry no durable proof that the process
-- tree was confirmed stopped. Mapping them to CANCELLED_CONFIRMED would assert
-- evidence that was never recorded, so the terminal tuple stays NULL and the row
-- remains queryable as
--   SELECT id FROM Execution WHERE status = 'cancelled' AND terminalDecision IS NULL;
UPDATE "Execution"
SET "dispatchState" = 'terminal'
WHERE "status" = 'cancelled';

-- Pre-start states were introduced by WP-C and may still be open on an existing
-- database. They are left untouched: their dispatch state is real history, and
-- Slice 1 does not fabricate the handshake messages they never persisted.

-- ---------------------------------------------------------------------------
-- 7. Triggers (10)
-- ---------------------------------------------------------------------------

-- T1. Terminal INSERT integrity: a row inserted directly as terminal must carry
--     the complete tuple, the matching decision and `phase = status`; a running
--     row must not pretend to be terminal. `terminalDecidedAt` is stored by
--     Prisma SQLite as an INTEGER number of Unix milliseconds, so the trigger
--     rejects TEXT dates, zero, negative and fractional values at the database
--     boundary instead of trusting the writer.
CREATE TRIGGER "Execution_terminal_insert_guard"
BEFORE INSERT ON "Execution"
FOR EACH ROW
BEGIN
    SELECT RAISE(ABORT, 'Execution_terminal_insert_guard: a terminal execution must have dispatchState=terminal, phase=status and endedAt')
    WHERE NEW."status" IN ('completed', 'failed', 'cancelled')
      AND (
            NEW."dispatchState" IS NOT 'terminal'
         OR NEW."phase" IS NOT NEW."status"
         OR NEW."endedAt" IS NULL
      );

    SELECT RAISE(ABORT, 'Execution_terminal_insert_guard: the terminal tuple must be complete and terminalDecidedAt must be a positive integer Unix ms')
    WHERE NEW."status" IN ('completed', 'failed', 'cancelled')
      AND (
            NEW."terminalDecision" IS NULL
         OR NEW."terminalDecidedAt" IS NULL
         OR typeof(NEW."terminalDecidedAt") <> 'integer'
         OR NEW."terminalDecidedAt" <= 0
         OR NEW."terminalDecidedBy" IS NULL
         OR length(trim(NEW."terminalDecidedBy")) = 0
      );

    SELECT RAISE(ABORT, 'Execution_terminal_insert_guard: terminalDecidedBy must use the API: or MIGRATION: prefix')
    WHERE NEW."status" IN ('completed', 'failed', 'cancelled')
      AND NEW."terminalDecidedBy" IS NOT NULL
      AND NOT (
            (NEW."terminalDecidedBy" GLOB 'API:*' AND length(NEW."terminalDecidedBy") > 4)
         OR (NEW."terminalDecidedBy" GLOB 'MIGRATION:*' AND length(NEW."terminalDecidedBy") > 10)
      );

    SELECT RAISE(ABORT, 'Execution_terminal_insert_guard: terminalDecision does not match the terminal status')
    WHERE NEW."status" IN ('completed', 'failed', 'cancelled')
      AND NEW."terminalDecision" IS NOT NULL
      AND NOT (
            (NEW."status" = 'completed' AND NEW."terminalDecision" = 'COMPLETED')
         OR (NEW."status" = 'cancelled' AND NEW."terminalDecision" = 'CANCELLED_CONFIRMED')
         OR (NEW."status" = 'failed' AND NEW."terminalDecision" IN (
                'EXECUTION_FAILED', 'START_REJECTED', 'START_ACCEPT_TIMEOUT',
                'START_SEND_UNCONFIRMED', 'RUNNER_DISCONNECTED', 'RUNNER_RESTARTED',
                'RUNNER_INTERRUPTED', 'RUNNER_START_UNCONFIRMED', 'RECOVERY_DEADLINE_EXCEEDED',
                'MESSAGE_INTEGRITY_FAILED', 'CLOCK_ANOMALY'))
      );

    SELECT RAISE(ABORT, 'Execution_terminal_insert_guard: a non-terminal execution must not carry a terminal tuple or dispatchState=terminal')
    WHERE NEW."status" NOT IN ('completed', 'failed', 'cancelled')
      AND (
            NEW."dispatchState" = 'terminal'
         OR NEW."terminalDecision" IS NOT NULL
         OR NEW."terminalDecidedAt" IS NOT NULL
         OR NEW."terminalDecidedBy" IS NOT NULL
      );
END;

-- T2. Terminal rows are immutable. First terminal writer wins; a late event may
--     append audit rows but never rewrites the decided outcome.
CREATE TRIGGER "Execution_terminal_update_guard"
BEFORE UPDATE ON "Execution"
FOR EACH ROW
WHEN OLD."status" IN ('completed', 'failed', 'cancelled')
BEGIN
    SELECT RAISE(ABORT, 'Execution_terminal_update_guard: a terminal execution is immutable (status, phase, dispatchState, terminal tuple, endedAt and exitCode cannot change)')
    WHERE NEW."status" IS NOT OLD."status"
       OR NEW."phase" IS NOT OLD."phase"
       OR NEW."dispatchState" IS NOT OLD."dispatchState"
       OR NEW."terminalDecision" IS NOT OLD."terminalDecision"
       OR NEW."terminalDecidedAt" IS NOT OLD."terminalDecidedAt"
       OR NEW."terminalDecidedBy" IS NOT OLD."terminalDecidedBy"
       OR NEW."endedAt" IS NOT OLD."endedAt"
       OR NEW."exitCode" IS NOT OLD."exitCode";
END;

-- T3. The only legal way into a terminal state is a complete, consistent write
--     from `running`: `phase = status`, a positive integer `terminalDecidedAt`,
--     a legal `terminalDecidedBy` and the decision that matches the status.
--     A running row may never carry a terminal tuple.
CREATE TRIGGER "Execution_terminal_write_guard"
BEFORE UPDATE ON "Execution"
FOR EACH ROW
BEGIN
    SELECT RAISE(ABORT, 'Execution_terminal_write_guard: leaving running requires dispatchState=terminal, phase=status and endedAt')
    WHERE OLD."status" = 'running'
      AND NEW."status" IN ('completed', 'failed', 'cancelled')
      AND (
            NEW."dispatchState" IS NOT 'terminal'
         OR NEW."phase" IS NOT NEW."status"
         OR NEW."endedAt" IS NULL
      );

    SELECT RAISE(ABORT, 'Execution_terminal_write_guard: the terminal tuple must be complete and terminalDecidedAt must be a positive integer Unix ms')
    WHERE OLD."status" = 'running'
      AND NEW."status" IN ('completed', 'failed', 'cancelled')
      AND (
            NEW."terminalDecision" IS NULL
         OR NEW."terminalDecidedAt" IS NULL
         OR typeof(NEW."terminalDecidedAt") <> 'integer'
         OR NEW."terminalDecidedAt" <= 0
         OR NEW."terminalDecidedBy" IS NULL
         OR length(trim(NEW."terminalDecidedBy")) = 0
      );

    SELECT RAISE(ABORT, 'Execution_terminal_write_guard: terminalDecidedBy must use the API: or MIGRATION: prefix')
    WHERE OLD."status" = 'running'
      AND NEW."status" IN ('completed', 'failed', 'cancelled')
      AND NEW."terminalDecidedBy" IS NOT NULL
      AND NOT (
            (NEW."terminalDecidedBy" GLOB 'API:*' AND length(NEW."terminalDecidedBy") > 4)
         OR (NEW."terminalDecidedBy" GLOB 'MIGRATION:*' AND length(NEW."terminalDecidedBy") > 10)
      );

    SELECT RAISE(ABORT, 'Execution_terminal_write_guard: terminalDecision does not match the terminal status')
    WHERE OLD."status" = 'running'
      AND NEW."status" IN ('completed', 'failed', 'cancelled')
      AND NEW."terminalDecision" IS NOT NULL
      AND NOT (
            (NEW."status" = 'completed' AND NEW."terminalDecision" = 'COMPLETED')
         OR (NEW."status" = 'cancelled' AND NEW."terminalDecision" = 'CANCELLED_CONFIRMED')
         OR (NEW."status" = 'failed' AND NEW."terminalDecision" IN (
                'EXECUTION_FAILED', 'START_REJECTED', 'START_ACCEPT_TIMEOUT',
                'START_SEND_UNCONFIRMED', 'RUNNER_DISCONNECTED', 'RUNNER_RESTARTED',
                'RUNNER_INTERRUPTED', 'RUNNER_START_UNCONFIRMED', 'RECOVERY_DEADLINE_EXCEEDED',
                'MESSAGE_INTEGRITY_FAILED', 'CLOCK_ANOMALY'))
      );

    SELECT RAISE(ABORT, 'Execution_terminal_write_guard: a running execution must not carry a terminal tuple or dispatchState=terminal')
    WHERE NEW."status" = 'running'
      AND (
            NEW."dispatchState" = 'terminal'
         OR NEW."terminalDecision" IS NOT NULL
         OR NEW."terminalDecidedAt" IS NOT NULL
         OR NEW."terminalDecidedBy" IS NOT NULL
      );

    SELECT RAISE(ABORT, 'Execution_terminal_write_guard: status may only leave running for a terminal value')
    WHERE OLD."status" = 'running'
      AND NEW."status" IS NOT OLD."status"
      AND NEW."status" NOT IN ('completed', 'failed', 'cancelled');
END;

-- T4. The six-state dispatch machine. No state may be added, skipped or left
--     without the durable evidence that justifies it.
CREATE TRIGGER "Execution_dispatch_transition_guard"
BEFORE UPDATE OF "dispatchState" ON "Execution"
FOR EACH ROW
WHEN NEW."dispatchState" IS NOT OLD."dispatchState"
BEGIN
    SELECT RAISE(ABORT, 'Execution_dispatch_transition_guard: illegal dispatchState transition')
    WHERE NOT (
            (OLD."dispatchState" = 'created' AND NEW."dispatchState" IN ('repository_preparing', 'terminal'))
         OR (OLD."dispatchState" = 'repository_preparing' AND NEW."dispatchState" IN ('repository_ready', 'terminal'))
         OR (OLD."dispatchState" = 'repository_ready' AND NEW."dispatchState" IN ('start_sent', 'terminal'))
         OR (OLD."dispatchState" = 'start_sent' AND NEW."dispatchState" IN ('running', 'terminal'))
         OR (OLD."dispatchState" = 'running' AND NEW."dispatchState" = 'terminal')
    );

    SELECT RAISE(ABORT, 'Execution_dispatch_transition_guard: dispatchState may only advance while the execution is running')
    WHERE NEW."dispatchState" <> 'terminal'
      AND NEW."status" <> 'running';

    SELECT RAISE(ABORT, 'Execution_dispatch_transition_guard: repository_preparing requires a persisted execution.repository message')
    WHERE NEW."dispatchState" = 'repository_preparing'
      AND NOT EXISTS (
            SELECT 1 FROM "RepositoryHandshakeMessage" AS m
            WHERE m."executionId" = NEW."id"
              AND m."messageType" = 'execution.repository'
              AND m."status" IN ('created', 'sent', 'acked')
      );

    SELECT RAISE(ABORT, 'Execution_dispatch_transition_guard: repository_ready requires a persisted repository message, a canonical path and repositoryPreparedAt')
    WHERE NEW."dispatchState" = 'repository_ready'
      AND (
            NEW."repositoryPreparedAt" IS NULL
         OR NEW."repositoryPath" IS NULL
         OR NOT EXISTS (
                SELECT 1 FROM "RepositoryHandshakeMessage" AS m
                WHERE m."executionId" = NEW."id"
                  AND m."messageType" = 'execution.repository'
                  AND m."status" IN ('created', 'sent', 'acked')
            )
      );

    SELECT RAISE(ABORT, 'Execution_dispatch_transition_guard: start_sent requires a persisted execution.start message and a start clock')
    WHERE NEW."dispatchState" = 'start_sent'
      AND (
            NEW."startSentAt" IS NULL
         OR NEW."startAcceptDeadlineAt" IS NULL
         OR NOT EXISTS (
                SELECT 1 FROM "RepositoryHandshakeMessage" AS m
                WHERE m."executionId" = NEW."id"
                  AND m."messageType" = 'execution.start'
                  AND m."status" IN ('created', 'sent', 'acked')
            )
      );
END;

-- T5. Start clock invariants: the start timestamps are write-once and the
--     recovery deadline can only be tightened, never extended.
CREATE TRIGGER "Execution_start_clock_guard"
BEFORE UPDATE OF "startSentAt", "startAcceptDeadlineAt", "recoveryDeadlineAt" ON "Execution"
FOR EACH ROW
BEGIN
    SELECT RAISE(ABORT, 'Execution_start_clock_guard: startSentAt and startAcceptDeadlineAt are write-once')
    WHERE (OLD."startSentAt" IS NOT NULL AND NEW."startSentAt" IS NOT OLD."startSentAt")
       OR (OLD."startAcceptDeadlineAt" IS NOT NULL AND NEW."startAcceptDeadlineAt" IS NOT OLD."startAcceptDeadlineAt");

    SELECT RAISE(ABORT, 'Execution_start_clock_guard: recoveryDeadlineAt may only move earlier')
    WHERE OLD."recoveryDeadlineAt" IS NOT NULL
      AND (NEW."recoveryDeadlineAt" IS NULL OR NEW."recoveryDeadlineAt" > OLD."recoveryDeadlineAt");

    SELECT RAISE(ABORT, 'Execution_start_clock_guard: the start accept deadline must follow startSentAt and precede the recovery deadline')
    WHERE NEW."startSentAt" IS NOT NULL
      AND (
            NEW."startAcceptDeadlineAt" IS NULL
         OR NEW."startAcceptDeadlineAt" <= NEW."startSentAt"
         OR (NEW."recoveryDeadlineAt" IS NOT NULL AND NEW."startAcceptDeadlineAt" > NEW."recoveryDeadlineAt")
      );
END;

-- T6. Registration epoch is monotonic and only advances by rotating the id.
--     An older registration can therefore never overwrite a newer one.
CREATE TRIGGER "Runner_registration_guard"
BEFORE UPDATE OF "registrationId", "registrationEpoch" ON "Runner"
FOR EACH ROW
BEGIN
    SELECT RAISE(ABORT, 'Runner_registration_guard: registrationEpoch cannot decrease')
    WHERE NEW."registrationEpoch" < OLD."registrationEpoch";

    SELECT RAISE(ABORT, 'Runner_registration_guard: registrationEpoch cannot skip a value')
    WHERE NEW."registrationEpoch" > OLD."registrationEpoch" + 1;

    SELECT RAISE(ABORT, 'Runner_registration_guard: advancing the epoch requires a new registrationId')
    WHERE NEW."registrationEpoch" = OLD."registrationEpoch" + 1
      AND (NEW."registrationId" IS NULL OR NEW."registrationId" IS OLD."registrationId");

    SELECT RAISE(ABORT, 'Runner_registration_guard: a new registrationId requires the next epoch')
    WHERE NEW."registrationId" IS NOT OLD."registrationId"
      AND NEW."registrationEpoch" IS NOT OLD."registrationEpoch" + 1;

    SELECT RAISE(ABORT, 'Runner_registration_guard: an established registrationId cannot be cleared')
    WHERE OLD."registrationId" IS NOT NULL AND NEW."registrationId" IS NULL;
END;

-- T7. Handshake message INSERT integrity.
CREATE TRIGGER "RepositoryHandshakeMessage_insert_guard"
BEFORE INSERT ON "RepositoryHandshakeMessage"
FOR EACH ROW
BEGIN
    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: messageType must be execution.repository or execution.start')
    WHERE NEW."messageType" NOT IN ('execution.repository', 'execution.start');

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: attempt must be at least 1')
    WHERE NEW."attempt" < 1;

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: payloadHash must be a lowercase sha256 hex digest')
    WHERE length(NEW."payloadHash") <> 64 OR NEW."payloadHash" GLOB '*[^0-9a-f]*';

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: envelopeJson must hold a canonical envelope')
    WHERE length(trim(NEW."envelopeJson")) = 0;

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: canonicalizationVersion is required')
    WHERE length(trim(NEW."canonicalizationVersion")) = 0;

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: createdRegistrationId and createdRegistrationEpoch are required')
    WHERE length(trim(NEW."createdRegistrationId")) = 0 OR NEW."createdRegistrationEpoch" < 0;

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: unknown message status')
    WHERE NEW."status" NOT IN ('created', 'sent', 'acked', 'rejected');

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: sent and acked messages require sentAt')
    WHERE NEW."status" IN ('sent', 'acked') AND NEW."sentAt" IS NULL;

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: acked messages require ackedAt')
    WHERE NEW."status" = 'acked' AND NEW."ackedAt" IS NULL;

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: a created message must not carry send or ack timestamps')
    WHERE NEW."status" = 'created' AND (NEW."sentAt" IS NOT NULL OR NEW."ackedAt" IS NOT NULL);

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_insert_guard: execution.start must never record a replay')
    WHERE NEW."messageType" = 'execution.start' AND NEW."lastReplayedAt" IS NOT NULL;
END;

-- T8. Handshake message UPDATE legality: identity is immutable, status only moves
--     forward, and a persisted start can never be turned into a replay source.
CREATE TRIGGER "RepositoryHandshakeMessage_update_guard"
BEFORE UPDATE ON "RepositoryHandshakeMessage"
FOR EACH ROW
BEGIN
    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_update_guard: message identity and envelope are immutable')
    WHERE NEW."executionId" IS NOT OLD."executionId"
       OR NEW."runnerId" IS NOT OLD."runnerId"
       OR NEW."messageType" IS NOT OLD."messageType"
       OR NEW."messageId" IS NOT OLD."messageId"
       OR NEW."protocolVersion" IS NOT OLD."protocolVersion"
       OR NEW."attempt" IS NOT OLD."attempt"
       OR NEW."envelopeJson" IS NOT OLD."envelopeJson"
       OR NEW."payloadHash" IS NOT OLD."payloadHash"
       OR NEW."canonicalizationVersion" IS NOT OLD."canonicalizationVersion"
       OR NEW."createdRegistrationId" IS NOT OLD."createdRegistrationId"
       OR NEW."createdRegistrationEpoch" IS NOT OLD."createdRegistrationEpoch"
       OR NEW."createdAt" IS NOT OLD."createdAt";

    -- `created -> acked` is allowed: a runner can only acknowledge a message it
    -- received, so the acknowledgement proves the send even when the `sent`
    -- write was not committed before it.
    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_update_guard: illegal message status transition')
    WHERE NEW."status" IS NOT OLD."status"
      AND NOT (
            (OLD."status" = 'created' AND NEW."status" IN ('sent', 'acked', 'rejected'))
         OR (OLD."status" = 'sent' AND NEW."status" IN ('acked', 'rejected'))
      );

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_update_guard: sentAt is write-once')
    WHERE OLD."sentAt" IS NOT NULL AND NEW."sentAt" IS NOT OLD."sentAt";

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_update_guard: ackedAt is write-once')
    WHERE OLD."ackedAt" IS NOT NULL AND NEW."ackedAt" IS NOT OLD."ackedAt";

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_update_guard: sent and acked statuses require their timestamps')
    WHERE (NEW."status" = 'sent' AND NEW."sentAt" IS NULL)
       OR (NEW."status" = 'acked' AND (NEW."sentAt" IS NULL OR NEW."ackedAt" IS NULL));

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_update_guard: execution.start must never be replayed')
    WHERE NEW."messageType" = 'execution.start' AND NEW."lastReplayedAt" IS NOT OLD."lastReplayedAt";

    SELECT RAISE(ABORT, 'RepositoryHandshakeMessage_update_guard: lastReplayedAt may only move forward')
    WHERE NEW."messageType" = 'execution.repository'
      AND NEW."lastReplayedAt" IS NOT NULL
      AND OLD."lastReplayedAt" IS NOT NULL
      AND NEW."lastReplayedAt" < OLD."lastReplayedAt";
END;

-- T9. Registration audit INSERT legitimacy.
--     * `adopted` takes over the immediately next registration epoch (the only
--       advance `Runner_registration_guard` permits).
--     * `rejected` must explain itself with a reasonCode and keeps history as
--       it was.
--     * `superseded` is the historical record of a registration that was
--       replaced: it requires the previous identity and a strictly newer epoch.
CREATE TRIGGER "ExecutionRegistrationAudit_insert_guard"
BEFORE INSERT ON "ExecutionRegistrationAudit"
FOR EACH ROW
BEGIN
    SELECT RAISE(ABORT, 'ExecutionRegistrationAudit_insert_guard: decision must be adopted, rejected or superseded')
    WHERE NEW."decision" NOT IN ('adopted', 'rejected', 'superseded');

    SELECT RAISE(ABORT, 'ExecutionRegistrationAudit_insert_guard: dispatchState must be one of the six frozen states')
    WHERE NEW."dispatchState" NOT IN ('created', 'repository_preparing', 'repository_ready', 'start_sent', 'running', 'terminal');

    SELECT RAISE(ABORT, 'ExecutionRegistrationAudit_insert_guard: a rejected takeover requires a reasonCode')
    WHERE NEW."decision" = 'rejected'
      AND (NEW."reasonCode" IS NULL OR length(trim(NEW."reasonCode")) = 0);

    SELECT RAISE(ABORT, 'ExecutionRegistrationAudit_insert_guard: newRegistrationId and a non-negative newRegistrationEpoch are required')
    WHERE length(trim(NEW."newRegistrationId")) = 0 OR NEW."newRegistrationEpoch" < 0;

    SELECT RAISE(ABORT, 'ExecutionRegistrationAudit_insert_guard: the new epoch must not roll back')
    WHERE NEW."previousRegistrationEpoch" IS NOT NULL
      AND NEW."newRegistrationEpoch" < NEW."previousRegistrationEpoch";

    SELECT RAISE(ABORT, 'ExecutionRegistrationAudit_insert_guard: an adopted takeover must advance the registration epoch by exactly one')
    WHERE NEW."decision" = 'adopted'
      AND NEW."previousRegistrationEpoch" IS NOT NULL
      AND NEW."newRegistrationEpoch" IS NOT NEW."previousRegistrationEpoch" + 1;

    SELECT RAISE(ABORT, 'ExecutionRegistrationAudit_insert_guard: a superseded registration requires the registration it replaced')
    WHERE NEW."decision" = 'superseded'
      AND (NEW."previousRegistrationId" IS NULL OR NEW."previousRegistrationEpoch" IS NULL);

    SELECT RAISE(ABORT, 'ExecutionRegistrationAudit_insert_guard: a superseded registration must be newer than the one it replaced')
    WHERE NEW."decision" = 'superseded'
      AND NEW."previousRegistrationEpoch" IS NOT NULL
      AND NEW."newRegistrationEpoch" <= NEW."previousRegistrationEpoch";
END;

-- T10. Audit rows are append-only. SQLite does not fire triggers for foreign-key
--      cascade actions, so deleting an Execution still removes its audit rows.
CREATE TRIGGER "ExecutionRegistrationAudit_no_update"
BEFORE UPDATE ON "ExecutionRegistrationAudit"
FOR EACH ROW
BEGIN
    SELECT RAISE(ABORT, 'ExecutionRegistrationAudit_no_update: registration audit rows are append-only');
END;

